"""Write the prompt templates verbatim to paper/tables/prompts_appendix.tex (Appendix A).

Usage: python -m experiments.make_prompt_appendix
"""
import textwrap
from pathlib import Path

from src.eval import faithfulness as F
from src.llm import prompts as P

ROOT = Path(__file__).resolve().parents[1]
WIDTH = 92


def block(title, text):
    lines = []
    for ln in text.splitlines():
        lines += textwrap.wrap(ln, WIDTH, subsequent_indent="  ", break_on_hyphens=False) or [""]
    body = "\n".join(lines)
    return f"\\paragraph{{{title}}}\n{{\\footnotesize\n\\begin{{verbatim}}\n{body}\n\\end{{verbatim}}\n}}\n"


def main():
    parts = [
        block(f"Grounded system prompt, {P.version('grounded', 'v1')} (main experiments).", P.SYSTEM_GROUNDED),
        block("Grounded user prompt (both versions).", P.USER_GROUNDED),
        block(f"Grounded system prompt, {P.version('grounded', 'v2')} (forced-citation experiment); differences from v1 are in rule 3 and the mechanism field.", P.SYSTEM_GROUNDED_V2),
        block(f"No-paths system and user prompts ({P.version('no_paths')}).", P.SYSTEM_NO_PATHS + "\n\n" + P.USER_NO_PATHS),
        block(f"Faithfulness judge system and user prompts ({F.JUDGE_VERSION}, judge {F.JUDGE_MODEL}).", F.JUDGE_SYSTEM + "\n\n" + F.JUDGE_USER),
    ]
    out = ROOT / "paper" / "tables" / "prompts_appendix.tex"
    out.write_text("% generated by experiments/make_prompt_appendix.py -- do not edit\n" + "\n".join(parts))
    print("wrote", out)


if __name__ == "__main__":
    main()
