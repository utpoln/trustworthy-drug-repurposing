"""Summary statistics for PrimeKG (kg.csv).

Reports nodes by type, edges by relation, and drug / disease / indication
counts, and writes a Markdown summary to results/tables/primekg_stats.md.

PrimeKG lists each edge in both directions (x->y and y->x), so edge counts
are given both as raw rows and as unique undirected edges.

Usage:
    python -m src.kg.explore [--kg data/raw/kg.csv] [--out results/tables/primekg_stats.md]
"""
import argparse
import hashlib
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_KG = ROOT / "data" / "raw" / "kg.csv"
DEFAULT_OUT = ROOT / "results" / "tables" / "primekg_stats.md"

# Dataverse: doi:10.7910/DVN/IXA7BM, version 2.1, file id 6180620
SOURCE = "Harvard Dataverse doi:10.7910/DVN/IXA7BM (v2.1), file kg.csv (id 6180620)"
EXPECTED_MD5 = "aac8191d4fbc5bf09cdf8c3c78b4e75f"

USECOLS = ["relation", "display_relation", "x_index", "x_type", "y_index", "y_type"]


def md5sum(path: Path, chunk: int = 1 << 20) -> str:
    h = hashlib.md5()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(chunk), b""):
            h.update(block)
    return h.hexdigest()


def load_kg(path: Path) -> pd.DataFrame:
    return pd.read_csv(
        path,
        usecols=USECOLS,
        dtype={
            "relation": "category",
            "display_relation": "category",
            "x_type": "category",
            "y_type": "category",
            "x_index": np.int64,
            "y_index": np.int64,
        },
        low_memory=False,
    )


def node_table(kg: pd.DataFrame) -> pd.DataFrame:
    nodes = pd.concat(
        [
            kg[["x_index", "x_type"]].set_axis(["node_index", "node_type"], axis=1),
            kg[["y_index", "y_type"]].set_axis(["node_index", "node_type"], axis=1),
        ],
        ignore_index=True,
    ).drop_duplicates("node_index")
    nodes["node_type"] = nodes["node_type"].astype(str)
    return nodes


def undirected(kg: pd.DataFrame) -> pd.DataFrame:
    """Drop the reverse copy of each edge: keep one row per (relation, {u, v})."""
    u = np.minimum(kg["x_index"].to_numpy(), kg["y_index"].to_numpy())
    v = np.maximum(kg["x_index"].to_numpy(), kg["y_index"].to_numpy())
    df = pd.DataFrame({"relation": kg["relation"].astype(str), "u": u, "v": v})
    return df.drop_duplicates()


def md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for row in df.itertuples(index=False):
        cells = [f"{c:,}" if isinstance(c, (int, np.integer)) else str(c) for c in row]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--kg", type=Path, default=DEFAULT_KG)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()

    print(f"Checksumming {args.kg} ...")
    md5 = md5sum(args.kg)
    md5_ok = md5 == EXPECTED_MD5
    print(f"  md5={md5} ({'matches' if md5_ok else 'DOES NOT MATCH'} Dataverse)")

    print("Loading ...")
    kg = load_kg(args.kg)
    n_rows = len(kg)

    # Nodes
    nodes = node_table(kg)
    nodes_by_type = (
        nodes["node_type"].value_counts().rename_axis("node_type").reset_index(name="count")
    )
    n_drugs = int((nodes["node_type"] == "drug").sum())
    n_diseases = int((nodes["node_type"] == "disease").sum())

    # Edges
    rows_by_rel = kg["relation"].astype(str).value_counts().rename("rows")
    und = undirected(kg)
    und_by_rel = und["relation"].value_counts().rename("undirected_edges")
    disp = (
        kg[["relation", "display_relation"]].astype(str).drop_duplicates()
        .groupby("relation")["display_relation"].agg(lambda s: ", ".join(sorted(s)))
    )
    edges_by_rel = (
        pd.concat([disp, rows_by_rel, und_by_rel], axis=1)
        .rename_axis("relation").reset_index()
        .sort_values("undirected_edges", ascending=False)
    )
    edges_by_rel["rows"] = edges_by_rel["rows"].astype(int)
    edges_by_rel["undirected_edges"] = edges_by_rel["undirected_edges"].astype(int)

    # Drug-disease relations
    dd_mask = ((kg["x_type"] == "drug") & (kg["y_type"] == "disease"))
    dd = kg.loc[dd_mask]
    dd_by_rel = dd["relation"].astype(str).value_counts()
    indication = dd.loc[dd["relation"] == "indication", ["x_index", "y_index"]].drop_duplicates()
    n_ind = len(indication)
    n_ind_drugs = indication["x_index"].nunique()
    n_ind_diseases = indication["y_index"].nunique()

    # Report
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    size_mb = args.kg.stat().st_size / 1e6
    md = f"""# PrimeKG summary statistics

Generated by `src/kg/explore.py` on {now}.

## Data provenance
- Source: {SOURCE}
- File: `{args.kg.relative_to(ROOT) if args.kg.is_relative_to(ROOT) else args.kg}` ({size_mb:,.1f} MB)
- MD5: `{md5}` ({'matches' if md5_ok else '**does not match**'} the Dataverse checksum)

## Overview
| metric | value |
|---|---|
| CSV rows (each edge appears in both directions) | {n_rows:,} |
| Unique undirected edges | {len(und):,} |
| Nodes | {len(nodes):,} |
| Node types | {nodes_by_type.shape[0]} |
| Relation types | {edges_by_rel.shape[0]} |
| Drugs | {n_drugs:,} |
| Diseases | {n_diseases:,} |
| Drug–disease `indication` edges (unique pairs) | {n_ind:,} |
| Drugs with at least one indication | {n_ind_drugs:,} |
| Diseases with at least one indication | {n_ind_diseases:,} |

## Drug–disease relations (unique pairs)
| relation | pairs |
|---|---|
""" + "\n".join(
        f"| {r} | {len(dd.loc[dd['relation'] == r, ['x_index', 'y_index']].drop_duplicates()):,} |"
        for r in dd_by_rel.index
    ) + f"""

## Nodes by type
{md_table(nodes_by_type)}

## Edges by relation
{md_table(edges_by_rel)}
"""
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(md)
    print(md)
    print(f"Saved {args.out}")


if __name__ == "__main__":
    main()
